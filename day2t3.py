transaction_cost = float(input("Enter transaction cost:"))
if transaction_cost < 1000:
    commission_fee = transaction_cost * 0.02
elif transaction_cost > 1000 and transaction_cost < 5000:
    commission_fee = transaction_cost * 0.10
else:
    commission_fee = transaction_cost * 0.05
total_cost = transaction_cost + commission_fee
print(f"The commission fee is:{commission_fee}")
print(f"The total cost is    :{total_cost}")





























































                                            




















    

























