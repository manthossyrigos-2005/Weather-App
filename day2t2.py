initial_capital_value = float(input("Enter initial capital value:   "))
final_capital_value   = float(input("Enter   final capital value:   "))
percentage_return     = 100*(final_capital_value - initial_capital_value)/(initial_capital_value)
print(f"το ποσοστοό κέρδους είναι:{percentage_return}%")
if percentage_return   >   0:
    print(f"Kέρδος η επένδυση είναι κερδοφόρα κατά : {percentage_return}%")
elif percentage_return <   0:
    print("Zημιά η επένδυση είναι ζημιογόνα")
else:
    print("Mηδενική μεταβολή κέρδους")
    























































                                            




















    

























